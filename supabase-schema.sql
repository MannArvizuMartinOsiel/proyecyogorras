create table if not exists public.user_profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null default '',
  street text not null default '',
  exterior_number text not null default '',
  interior_number text not null default '',
  neighborhood text not null default '',
  postal_code text not null default '',
  city text not null default '',
  state text not null default '',
  phone text not null default '',
  privacy_policy_version text not null default '',
  privacy_consent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.user_profiles
  add column if not exists privacy_policy_version text not null default '',
  add column if not exists privacy_consent_at timestamptz;

alter table public.user_profiles enable row level security;

drop policy if exists "Users can view their own profile" on public.user_profiles;
create policy "Users can view their own profile"
  on public.user_profiles for select
  to authenticated
  using ((select auth.uid()) = id);

drop policy if exists "Users can create their own profile" on public.user_profiles;
create policy "Users can create their own profile"
  on public.user_profiles for insert
  to authenticated
  with check ((select auth.uid()) = id);

drop policy if exists "Users can update their own profile" on public.user_profiles;
create policy "Users can update their own profile"
  on public.user_profiles for update
  to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

grant select, insert, update on public.user_profiles to authenticated;

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  stripe_checkout_session_id text unique,
  paypal_order_id text unique,
  payment_provider text not null default 'stripe'
    check (payment_provider in ('stripe', 'paypal')),
  subtotal integer not null default 0 check (subtotal >= 0),
  discount_amount integer not null default 0 check (discount_amount >= 0),
  promo_code text,
  amount integer not null check (amount >= 0),
  currency text not null default 'mxn',
  status text not null default 'pending'
    check (status in ('pending', 'paid', 'failed', 'cancelled')),
  items jsonb not null default '[]'::jsonb,
  shipping_address jsonb,
  customer_email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.orders
  alter column stripe_checkout_session_id drop not null,
  add column if not exists paypal_order_id text,
  add column if not exists payment_provider text not null default 'stripe',
  add column if not exists subtotal integer not null default 0,
  add column if not exists discount_amount integer not null default 0,
  add column if not exists promo_code text;

alter table public.orders
  drop constraint if exists orders_payment_provider_check,
  add constraint orders_payment_provider_check
    check (payment_provider in ('stripe', 'paypal'));

create unique index if not exists orders_paypal_order_id_key
  on public.orders (paypal_order_id)
  where paypal_order_id is not null;

alter table public.orders enable row level security;

drop policy if exists "Users can view their own orders" on public.orders;
create policy "Users can view their own orders"
  on public.orders for select
  to authenticated
  using ((select auth.uid()) = user_id);

grant select on public.orders to authenticated;

create table if not exists public.admin_products (
  id bigint generated by default as identity (start with 1000) primary key,
  department text not null check (department in ('Gorras', 'Ropa', 'Joyería', 'Tenis')),
  category text,
  type text not null check (type in ('cap', 'shirt', 'hoodie', 'chain', 'bracelet', 'sneaker')),
  name text not null check (char_length(name) between 1 and 80),
  description text not null check (char_length(description) between 1 and 300),
  price integer not null check (price between 1 and 1000000),
  color text not null,
  brim text not null,
  patch text,
  label text not null,
  image_url text,
  created_at timestamptz not null default now()
);

alter table public.admin_products
  add column if not exists image_url text;

alter table public.admin_products enable row level security;
revoke all on public.admin_products from anon, authenticated;
grant select, insert on public.admin_products to service_role;
grant usage, select on sequence public.admin_products_id_seq to service_role;

